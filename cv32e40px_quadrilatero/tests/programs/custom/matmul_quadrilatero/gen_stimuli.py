import sys
import random
import math
M = 16
N = 16
K = 16

A_dtype = "int8_t"
B_dtype = "int8_t"
C_dtype = "int32_t"

header_file = "matrixData.h"

def datatype_width(dtype):
    if dtype == "int32_t" or dtype == "uint32_t": 
        return 32
    elif dtype == "int16_t" or dtype == "uint16_t": 
        return 16
    elif dtype == "int8_t" or dtype == "uint8_t": 
        return 8
    else: raise ValueError("Unsupported data type: {}".format(dtype))

# mapping used in quadrilatero
def get_quadrilatero_dt(dtype):
    if dtype == "int8_t":   return 0    # __INT8__
    elif dtype == "int16_t":  return 1  # __INT16__
    elif dtype == "int32_t":  return 2  # __INT32__
    elif dtype == "uint8_t":  return 8  # __UINT8__
    elif dtype == "uint16_t": return 9  # __UINT16__
    elif dtype == "uint32_t": return 10 # __UINT32__
    else: return 0

def write_arr(f, name, arr, ctype, size):
    f.write(f'{ctype} __attribute__((section(".data"))) {name}[] = {{\n')
    for i, v in enumerate(arr, 1):
        terminator = ",\n" if i % size == 0 else ","
        f.write(f'{v}{terminator}')
    f.write('};\n\n')


matA = []
matBT = []
matC_gold = []

for i in range(M):
    for j in range(K):
        a = random.randint(-2**(datatype_width(A_dtype)-1), 2**(datatype_width(A_dtype)-1)-1)
        matA.append(a)

for i in range(N):
    for j in range(K):
        b = random.randint(-2**(datatype_width(B_dtype)-1), 2**(datatype_width(B_dtype)-1)-1)
        matBT.append(b)

for i in range(M):
    for j in range(N):
        r = 0
        for k in range(K):
            r += matA[i*K + k] * matBT[j*K + k]
        matC_gold.append(r)

f = open(header_file, 'w')
f.write('#ifndef _MATRIX_DATA_\n')
f.write('#define _MATRIX_DATA_\n')

f.write('// This file is automatically generated\n\n')
f.write(f'#define DIM_M {M}\n')
f.write(f'#define DIM_N {N}\n')
f.write(f'#define DIM_K {K}\n\n')

f.write(f'#define A_DTYPE {A_dtype}\n')
f.write(f'#define B_DTYPE {B_dtype}\n')
f.write(f'#define C_DTYPE {C_dtype}\n\n')

f.write(f'#define DTC {get_quadrilatero_dt(C_dtype)}\n')
f.write(f'#define DTA {get_quadrilatero_dt(A_dtype)}\n')
f.write(f'#define DTB {get_quadrilatero_dt(B_dtype)}\n')

widening = int(math.log2(datatype_width(C_dtype) / datatype_width(A_dtype)))
f.write(f'#define WIDENING {widening}\n\n')

f.write(f'#define RMUL_2 1\n') 
f.write(f'#define CMUL_2 1\n\n')
f.write(f'#define FUNC_NAME matmul_custom\n\n')

write_arr(f, 'matA', matA, A_dtype, K)
write_arr(f, 'matBT', matBT, B_dtype, K)
write_arr(f, 'matC_gold', matC_gold, C_dtype, N)

f.write('#endif // _MATRIX_DATA_\n')